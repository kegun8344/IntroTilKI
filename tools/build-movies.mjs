// Builds js/movies.js from data/movies.txt and checks every line.
// Usage: node tools/build-movies.mjs        (exit code 1 if any line is invalid)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(root, "data", "movies.txt");
const OUT = path.join(root, "js", "movies.js");

export const GENRES = ["Action", "Adventure", "Animation", "Comedy", "Crime", "Documentary", "Drama", "Family",
  "Fantasy", "History", "Horror", "Musical", "Mystery", "Romance", "Sci-Fi", "Sport", "Thriller", "War", "Western"];
export const COUNTRIES = {
  US: "USA", GB: "UK", IE: "Ireland", CA: "Canada", AU: "Australia", NZ: "New Zealand",
  NO: "Norway", SE: "Sweden", DK: "Denmark", FI: "Finland", IS: "Iceland",
  FR: "France", DE: "Germany", IT: "Italy", ES: "Spain", LV: "Latvia",
  KR: "South Korea", JP: "Japan", CN: "China", HK: "Hong Kong", TW: "Taiwan", IN: "India", IR: "Iran",
  MX: "Mexico", BR: "Brazil", AR: "Argentina", ZA: "South Africa"
};

// Stable short id from title + year (FNV-1a, base36), so share links survive edits to the list.
function idFor(title, year) {
  let h = 0x811c9dc5;
  for (const ch of title.toLowerCase() + "|" + year) { h ^= ch.codePointAt(0); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(36).padStart(7, "0").slice(0, 7);
}

export function parse(text) {
  const movies = [], errors = [], seen = new Map(), ids = new Map();
  text.split(/\r?\n/).forEach((raw, i) => {
    const line = raw.trim(), n = i + 1;
    if (!line || line.startsWith("#")) return;
    const f = line.split("|").map(s => s.trim());
    const err = msg => errors.push(`line ${n}: ${msg}  →  ${line.slice(0, 70)}`);
    if (f.length !== 8) return err(`expected 8 fields, got ${f.length}`);
    const [title, y, rt, g, country, director, cast, pitch] = f;
    const year = Number(y), runtime = Number(rt);
    const genres = g.split(",").map(s => s.trim()).filter(Boolean);
    if (!title) err("missing title");
    if (!Number.isInteger(year) || year < 1920 || year > 2026) err(`bad year "${y}"`);
    if (!Number.isInteger(runtime) || runtime < 60 || runtime > 260) err(`bad runtime "${rt}"`);
    if (!genres.length || genres.length > 3) err("needs 1–3 genres");
    genres.filter(x => !GENRES.includes(x)).forEach(x => err(`unknown genre "${x}"`));
    if (!COUNTRIES[country]) err(`unknown country code "${country}"`);
    if (!director) err("missing director");
    if (pitch.length < 15 || pitch.length > 110) err(`pitch length ${pitch.length} (15–110)`);
    if (!/[.!?]$/.test(pitch)) err("pitch should end with . ! or ?");
    const key = title.toLowerCase() + "|" + year;
    if (seen.has(key)) err(`duplicate of line ${seen.get(key)}`);
    seen.set(key, n);
    const id = idFor(title, year);
    if (ids.has(id) && ids.get(id) !== key) err(`id collision ${id}`);
    ids.set(id, key);
    movies.push({
      id, title, year, runtime, genres, country,
      director, cast: cast.split(";").map(s => s.trim()).filter(s => s && s !== "-"), pitch
    });
  });
  return { movies, errors };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { movies, errors } = parse(fs.readFileSync(SRC, "utf8"));
  if (errors.length) {
    console.error(errors.join("\n"));
    console.error(`\n${errors.length} problem(s). js/movies.js was NOT updated.`);
    process.exit(1);
  }
  const body = movies.map(m => "    " + JSON.stringify(m)).join(",\n");
  const out = `/*
 * GENERATED by tools/build-movies.mjs from data/movies.txt. Edit the .txt file, not this one.
 * ${movies.length} movies. Titles, years, runtimes (approx.), directors and cast are public facts;
 * the one-line pitches are written for this app. No posters or images are used.
 */
(function (root) {
  var MOVIES = [
${body}
  ];
  var COUNTRIES = ${JSON.stringify(COUNTRIES)};
  if (typeof module !== "undefined" && module.exports) { module.exports = MOVIES; module.exports.COUNTRIES = COUNTRIES; }
  else { root.MOVIES = MOVIES; root.COUNTRIES = COUNTRIES; }
})(this);
`;
  fs.writeFileSync(OUT, out);
  const byCountry = {};
  movies.forEach(m => byCountry[m.country] = (byCountry[m.country] || 0) + 1);
  console.log(`OK: ${movies.length} movies written to js/movies.js`);
  console.log("By country:", Object.entries(byCountry).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(", "));
}
